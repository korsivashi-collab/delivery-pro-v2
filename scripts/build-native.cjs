const fs = require('node:fs');
const path = require('node:path');
require('./prepare-capacitor.cjs');
const root = path.resolve(__dirname, '..');
const output = path.resolve(root, 'www');
// 재빌드 시 과거 결제 페이지나 서버 파일이 남지 않도록 생성 전용 디렉터리만 정리합니다.
if (path.dirname(output) !== root || path.basename(output) !== 'www') throw new Error('Invalid output directory');
if (fs.existsSync(output) && fs.lstatSync(output).isSymbolicLink()) throw new Error('www must not be a symlink');
if (fs.existsSync(output) && fs.readdirSync(output).length && !fs.existsSync(path.join(output, '.native-generated'))) {
    throw new Error('www contains unmanaged files. Move them before building.');
}
fs.rmSync(output, { recursive: true, force: true });
fs.mkdirSync(output, { recursive: true });
fs.writeFileSync(path.join(output, '.native-generated'), 'Generated by scripts/build-native.cjs\n');
const copied = new Set();
const iconAssets = new Set([
    'icons/header-logo-06-640.png',
    'icons/icon-pro-192.png',
    'icons/icon-pro-512.png'
]);
function copy(relative) {
    relative = relative.replace(/\\/g, '/');
    // Fail on new references instead of shipping unnecessary icons or broken links.
    if (relative.startsWith('icons/') && !iconAssets.has(relative)) {
        throw new Error('Icon is not included in the native asset allowlist: ' + relative);
    }
    const source = path.resolve(root, relative);
    if (!source.startsWith(root + path.sep) || !/^(?:js[\\/]|icons[\\/]|css[\\/]|(?:index|terms|privacy|policy|error)\.html$|manifest\.json$)/.test(relative)) {
        throw new Error('Asset outside allowed client paths: ' + relative);
    }
    if (copied.has(relative)) return;
    copied.add(relative);
    const destination = path.join(output, relative);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(source, destination);
    if (!/\.(?:html|js|json|css)$/.test(relative)) return;
    const text = fs.readFileSync(source, 'utf8');
    if (/payment\.html|success-payment\.html|tosspayments|payment-confirm/i.test(text)) {
        throw new Error('External billing found in native assets: ' + relative);
    }
    if (relative.endsWith('.js') && !relative.replace(/\\/g, '/').startsWith('js/vendor/')) {
        for (const match of text.matchAll(/(?:from\s*|import\s*(?:\(\s*)?)["'](\.[^"']+)["']/g)) {
            copy(path.relative(root, path.resolve(path.dirname(source), match[1])));
        }
    }
    for (const match of text.matchAll(/(?:src|href)=["'](\.?\/?(?:js|css|icons)\/[^"']+)["']/g)) copy(match[1].replace(/^\.?\//, ''));
    for (const match of text.matchAll(/["'](icons\/[^"']+\.(?:png|svg|webp|ico))["']/g)) copy(match[1]);
}
for (const file of ['index.html', 'terms.html', 'privacy.html', 'policy.html', 'manifest.json', 'error.html', 'js/app.js', 'js/vendor/capacitor.LICENSE']) copy(file);
console.log(`Native web root ready: www (${copied.size} assets, no web checkout or server code)`);
